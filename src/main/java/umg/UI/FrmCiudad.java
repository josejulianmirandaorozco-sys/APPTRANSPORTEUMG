    public void listar() {
    try {
        CiudadDAO dao = new CiudadDAO();
        List<Ciudad> lista = dao.listar();
        
        // Obtener el modelo de la tabla
        DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
        modelo.setRowCount(0); // Limpiar filas anteriores
        
        // Llenar filas
        for (Ciudad c : lista) {
            modelo.addRow(new Object[]{c.getCiudad(), c.getNombre()});
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar datos: " + e.getMessage());
    }
}
    
    
    
